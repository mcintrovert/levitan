def camel(words):
    """['обработка','проведения'] -> 'ОбработкаПроведения'."""
    return "".join(w[:1].upper() + w[1:] for w in words if w)


def _apply_symbols(s):
    for phrase, sym in SYMBOLS:
        s = re.sub(r"\b" + re.escape(phrase) + r"\b", sym, s, flags=re.IGNORECASE)
    return s


def _apply_phrases(s):
    """Многословные ключевые слова и термины 1С -> как пишется в коде."""
    for phrase, repl in MULTIWORD + TERMS:
        s = re.sub(r"(?<![А-Яа-яЁё])" + re.escape(phrase) + r"(?![А-Яа-яЁё])",
                   repl, s, flags=re.IGNORECASE)
    return s


_PUNCT = ".,!?;:…"


def _norm(word):
    """Слово без пунктуации по краям — для сравнения с триггерами.

    Whisper расставляет знаки сам, и «Для каждого, строка из товары цикл»
    приходит с запятой внутри конструкции. Без очистки триггер «для каждого»
    не опознаётся, и цикл не разворачивается.
    """
    return word.strip(_PUNCT).lower()


def _drop_tail_word(words, tail):
    """Убрать хвостовое слово, если оно есть: «… из товары цикл» -> «… из товары».

    Человек диктует конструкцию целиком, как она звучит в коде. Слово «цикл»
    в конце — часть конструкции, а не имя коллекции, и в имя попадать не должно.
    """
    if words and _norm(words[-1]) == tail:
        return words[:-1]
    return words


def _cap_words(s):
    """Ключевые слова -> правильный регистр; прочие идентификаторы -> с Заглавной
    (в 1С почти всё именуется с большой буквы: Сумма, Контрагент, Выборка)."""
    def repl(m):
        w = m.group(0)
        kw = KEYWORDS.get(w.lower())
        if kw:
            return kw
        return w[:1].upper() + w[1:]
    return re.sub(r"[А-Яа-яЁё][А-Яа-яЁё0-9]*", repl, s)


def _clean_spaces(s):
    s = re.sub(r"[ \t]+", " ", s)
    s = re.sub(r"\s*\.\s*", ".", s)        # плотная точка: Выборка . Контрагент -> Выборка.Контрагент
    s = re.sub(r" ([;,)\]])", r"\1", s)    # нет пробела перед ; , ) ]
    s = re.sub(r"([(\[]) ", r"\1", s)      # нет пробела после ( [
    return s.strip()


def _line(s):
    """Обычная строка кода: фразы + символы + регистр слов + косметика."""
    return _clean_spaces(_cap_words(_apply_symbols(_apply_phrases(s))))


def _strip_trigger(words, trigger_len):
    return words[trigger_len:]


def to_code(text):
    """Главный вход: речь -> код 1С (со скелетами и курсором ‸)."""
    raw = text.strip().rstrip(".").strip()
    if not raw:
        return ""
    words = raw.split()
    low = [_norm(w) for w in words]

    # --- Процедура ---
    if low[0] == "процедура":
        rest = _strip_trigger(words, 1)
        export = ""
        if rest and _norm(rest[-1]) == "экспорт":
            export = " Экспорт"
            rest = rest[:-1]
        name = camel([_norm(w) for w in rest]) or "ИмяПроцедуры"
        return (f"Процедура {name}(){export}\n"
                f"\t{CARET}\n"
                f"КонецПроцедуры")

    # --- Функция ---
    if low[0] == "функция":
        rest = _strip_trigger(words, 1)
        export = ""
        if rest and _norm(rest[-1]) == "экспорт":
            export = " Экспорт"
            rest = rest[:-1]
        name = camel([_norm(w) for w in rest]) or "ИмяФункции"
        return (f"Функция {name}(){export}\n"
                f"\tВозврат {CARET};\n"
                f"КонецФункции")

    # --- ИначеЕсли ---
    if low[:2] == ["иначе", "если"] or low[0] == "иначеесли":
        tail = words[2:] if low[:2] == ["иначе", "если"] else words[1:]
        cond = _line(" ".join(_drop_tail_word(tail, "тогда")))
        return f"ИначеЕсли {cond or CARET} Тогда\n\t"

    # --- Иначе ---
    if low[0] == "иначе":
        return f"Иначе\n\t{CARET}"

    # --- Если ---
    if low[0] == "если":
        cond = _line(" ".join(_drop_tail_word(words[1:], "тогда")))
        return (f"Если {cond or CARET} Тогда\n"
                f"\t{CARET}\n"
                f"КонецЕсли;")

    # --- Для Каждого … Из … Цикл ---
    if low[:2] == ["для", "каждого"]:
        rest = _drop_tail_word(words[2:], "цикл")
        var, coll = CARET, CARET
        if "из" in [_norm(w) for w in rest]:
            i = [_norm(w) for w in rest].index("из")
            var = camel([_norm(w) for w in rest[:i]]) or CARET
            coll = camel([_norm(w) for w in rest[i + 1:]]) or CARET
        return (f"Для Каждого {var} Из {coll} Цикл\n"
                f"\t{CARET}\n"
                f"КонецЦикла;")

    # --- Для Счётчик = 1 По N Цикл ---
    if low[0] == "для":
        rest = _drop_tail_word(words[1:], "цикл")
        low_rest = [_norm(w) for w in rest]
        if "по" in low_rest:
            i = low_rest.index("по")
            head = _line(" ".join(rest[:i])) or CARET
            limit = _line(" ".join(rest[i + 1:])) or CARET
            if "=" not in head:                     # «для сч 1 по 10» без «равно»
                parts = head.split()
                if len(parts) >= 2:
                    head = f"{parts[0]} = {' '.join(parts[1:])}"
                else:
                    head = f"{head} = 1"
            return (f"Для {head} По {limit} Цикл\n"
                    f"\t{CARET}\n"
                    f"КонецЦикла;")

    # --- Пока … Цикл ---
    if low[0] == "пока":
        cond = _line(" ".join(_drop_tail_word(words[1:], "цикл")))
        return (f"Пока {cond or CARET} Цикл\n"
                f"\t{CARET}\n"
                f"КонецЦикла;")

    # --- Попытка ---
    if low[0] == "попытка":
        return (f"Попытка\n"
                f"\t{CARET}\n"
                f"Исключение\n"
                f"\t\n"
                f"КонецПопытки;")

    # --- Возврат ---
    if low[0] == "возврат":
        val = _line(" ".join(words[1:]))
        return f"Возврат {val};".replace(" ;", ";")

    # --- обычная строка кода ---
    return _line(raw)


def strip_caret(s):
    return s.replace(CARET, "")


def active_window_is_1c():
    """True, если активное окно — 1С Конфигуратор (для авто-режима «код»).
    Определяем по заголовку окна (содержит 'Конфигуратор')."""
    try:
        import ctypes
        u = ctypes.windll.user32
        h = u.GetForegroundWindow()
        length = u.GetWindowTextLengthW(h)
        buf = ctypes.create_unicode_buffer(length + 1)
        u.GetWindowTextW(h, buf, length + 1)
        return "конфигуратор" in buf.value.lower()
    except Exception:
        return False
